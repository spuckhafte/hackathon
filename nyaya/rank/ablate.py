"""End-to-end ablations: stemming on/off and act-inheritance on/off.

These sit beside the index-level numbers (vocabulary, postings) already measured
in `nyaya.index.stats`.  The index-level figures say what an option costs; these
say what it is worth, which is the question that matters.

Both ablations need their own index, because both change how documents are
analysed — you cannot ablate stemming at query time against a stemmed index.
`runs/ablations.json` is regenerated by exactly this sequence, in this order
(each ``--build`` writes ``index/<arm>/``; the three builds are independent and
only need doing once)::

    python -m nyaya.rank.ablate --build nostem
    python -m nyaya.rank.ablate --build nocanon
    python -m nyaya.rank.ablate --build noinherit
    python -m nyaya.rank.ablate --run --split test --mode S4

``--run`` scores every arm in `ARMS`, prints the table and writes
`runs/ablations.json`.  An arm whose index is missing is reported as
``not built`` and skipped rather than silently dropped, so a partial run cannot
be mistaken for a complete one.

**The query side is switched with the index side.** `normalise.STEM_QUERIES` is
flipped together with the index path; running a stemmed query against an
unstemmed index is not an ablation, it is a broken system, and it would make the
ablation look far better than it is.

Author: Sumedha (M3)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from nyaya import config

__all__ = ["ARMS", "run_arm", "build_arm"]

#: name -> (index subdirectory, profile kwargs, what it turns off)
ARMS: Dict[str, Dict[str, Any]] = {
    "full": {
        "path": None, "stem_queries": True, "inherit_act": True,
        "what": "the shipped analyser: canonicalisation, inheritance, stemming",
    },
    "nostem": {
        "path": "nostem", "stem_queries": False, "inherit_act": True,
        "profile": dict(canonicalise=True, stem=False, zoned=True,
                        stoplist="legal"),
        "what": "Porter stemming off, on both the document and the query side",
    },
    "nocanon": {
        "path": "nocanon", "stem_queries": True, "inherit_act": True,
        "profile": dict(canonicalise=False, stem=True, zoned=True,
                        stoplist="legal"),
        "what": "statute canonicalisation off (so no ipc§302 tokens anywhere)",
    },
    "noinherit": {
        "path": "noinherit", "stem_queries": True, "inherit_act": False,
        "profile": dict(canonicalise=True, stem=True, zoned=True,
                        stoplist="legal"),
        "what": ("canonicalisation on but act inheritance off, so a bare "
                 "'Section 34' in a judgment stays plain text"),
    },
}


def build_arm(name: str, processes: Optional[int] = None) -> Path:
    """Build the index one arm needs.  Must be called under a __main__ guard:
    Windows spawns workers by re-importing the entry module."""
    from nyaya.index.positional import IndexProfile, build

    arm = ARMS[name]
    if not arm.get("profile"):
        raise ValueError(f"{name} uses the shipped index; nothing to build")
    from nyaya import statutes

    out = config.INDEX / arm["path"]
    saved = statutes.INHERIT_ACT_DEFAULT
    try:
        # The builder profile has no inheritance flag, so this arm is built with
        # the canonicaliser's own default flipped.  `canonicalise_statutes`
        # reads it live, and the worker processes re-import this module, so the
        # flip has to survive a spawn - hence the module-level default rather
        # than a keyword threaded through.
        statutes.INHERIT_ACT_DEFAULT = bool(arm.get("inherit_act", True))
        build(IndexProfile(name=name, out=out, **arm["profile"]),
              processes=processes, verbose=True)
    finally:
        statutes.INHERIT_ACT_DEFAULT = saved
    return out


def run_arm(name: str, queries: Sequence[Dict], qrels: Dict[str, Dict[int, int]],
            mode: str = "S4", k: int = 10) -> Dict[str, Any]:
    """Score one arm, switching the query analyser to match its index."""
    from nyaya.index.positional import PositionalIndex
    from nyaya.query import normalise as N
    from nyaya.rank.tune import evaluate
    from nyaya.search import MODE_SETTINGS, load_context
    from nyaya.statutes import INHERIT_ACT_DEFAULT

    arm = ARMS[name]
    path = config.INDEX / arm["path"] if arm["path"] else config.INDEX
    if not (path / "dictionary.json").exists():
        return {"arm": name, "error": f"{path} is not built"}

    ctx = load_context(mode)
    saved_index, saved_stem = ctx.index, N.STEM_QUERIES
    try:
        ctx.index = PositionalIndex.load(path)
        N.STEM_QUERIES = bool(arm["stem_queries"])
        sc = evaluate(queries, qrels, mode=mode, k=k, ctx=ctx)
        st = ctx.index.stats()
        return {
            "arm": name, "what": arm["what"], "index": str(path),
            "ndcg": sc.ndcg, "map": sc.map, "p10": sc.p10,
            "vocabulary": st["vocabulary"], "postings": st["total_postings"],
            "on_disk": st["on_disk_total"], "seconds": round(sc.seconds, 1),
            "per_query": sc.per_query,
        }
    finally:
        ctx.index, N.STEM_QUERIES = saved_index, saved_stem


def _main(argv: Optional[Sequence[str]] = None) -> int:       # pragma: no cover
    from nyaya.utils import ensure_utf8_stdout

    ensure_utf8_stdout()
    ap = argparse.ArgumentParser(prog="python -m nyaya.rank.ablate")
    ap.add_argument("--build", choices=[a for a in ARMS if ARMS[a].get("profile")])
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--mode", default="S4")
    ap.add_argument("--split", default="test")
    ap.add_argument("-k", type=int, default=10)
    args = ap.parse_args(argv)

    if args.build:
        build_arm(args.build)
        return 0
    if not args.run:
        ap.print_help()
        return 0

    from nyaya.rank.tune import load_dev

    queries, qrels = load_dev(args.split)
    print(f"{len(queries)} {args.split} queries, mode {args.mode}\n")
    rows = [run_arm(a, queries, qrels, mode=args.mode, k=args.k) for a in ARMS]
    base = rows[0]

    print(f"{'arm':<9}{'nDCG@10':>9}{'MAP':>8}{'P@10':>7}"
          f"{'d nDCG':>9}{'vocab':>10}{'postings':>12}{'on disk':>10}")
    print("-" * 74)
    for r in rows:
        if "error" in r:
            print(f"{r['arm']:<9}  {r['error']}")
            continue
        d = r["ndcg"] - base["ndcg"] if r is not base else 0.0
        print(f"{r['arm']:<9}{r['ndcg']:>9.4f}{r['map']:>8.4f}{r['p10']:>7.3f}"
              f"{d:>+9.4f}{r['vocabulary']:>10,}{r['postings']:>12,}"
              f"{r['on_disk']:>10}")
    print()
    for r in rows:
        if "what" in r:
            print(f"  {r['arm']:<9}{r['what']}")

    # the inheritance ablation is a *canonicaliser* switch, not an index one
    print()
    print(_inherit_ablation(queries, qrels, args.mode, args.k))

    out = config.RUNS / "ablations.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"split": args.split, "mode": args.mode,
                               "arms": rows}, indent=1), encoding="utf-8")
    print(f"\nwritten to {out}")
    return 0


def _inherit_ablation(queries, qrels, mode: str, k: int) -> str:
    """Act inheritance off, on the query side only.

    The index cannot be re-analysed per arm here without a third build, so what
    this measures is narrower and is labelled as such: with inheritance off, a
    *query* like "sec. 302" no longer resolves to ``ipc§302``, while the
    documents keep the tokens inheritance gave them.
    """
    from nyaya import statutes
    from nyaya.rank.tune import evaluate
    from nyaya.search import load_context

    ctx = load_context(mode)
    saved = statutes.INHERIT_ACT_DEFAULT
    try:
        on = evaluate(queries, qrels, mode=mode, k=k, ctx=ctx)
        statutes.INHERIT_ACT_DEFAULT = False
        off = evaluate(queries, qrels, mode=mode, k=k, ctx=ctx)
    finally:
        statutes.INHERIT_ACT_DEFAULT = saved
    return (f"act inheritance (query side only; the index keeps its tokens)\n"
            f"  on   nDCG@10 {on.ndcg:.4f}  MAP {on.map:.4f}\n"
            f"  off  nDCG@10 {off.ndcg:.4f}  MAP {off.map:.4f}  "
            f"({off.ndcg - on.ndcg:+.4f})")


if __name__ == "__main__":                                   # pragma: no cover
    raise SystemExit(_main())
