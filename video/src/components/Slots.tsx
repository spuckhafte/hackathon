/**
 * The two kinds of *gap* in the film.
 *
 * The brief requires the video to show the system running live and each member
 * explaining their own component, so most of the timeline is not animation. A
 * slot renders either:
 *
 *   - the real footage, if `public/footage/<name>.mp4` exists, or
 *   - a labelled placeholder frame that tells the editor exactly what to
 *     capture, for how long, and (for screen slots) which command to run.
 *
 * Existence is probed at render time with a HEAD request against the static
 * file server, so dropping a file into `public/footage/` and re-rendering is
 * the whole workflow - nothing has to be regenerated by hand.
 */
import React, {useEffect, useState} from 'react';
import {
  AbsoluteFill,
  continueRender,
  delayRender,
  interpolate,
  OffthreadVideo,
  staticFile,
  useCurrentFrame,
  useVideoConfig,
} from 'remotion';
import {COLORS, SIZES} from '../theme';
import {FONT_MONO, FONT_SANS} from '../fonts';
import {Backdrop, useEnter} from './primitives';
import type {Person} from '../data';

// ---------------------------------------------------------------------------
// footage probe
// ---------------------------------------------------------------------------

type Probe = 'pending' | 'found' | 'missing';

const useFootage = (name: string): {state: Probe; src: string} => {
  const src = staticFile(`footage/${name}.mp4`);
  const [state, setState] = useState<Probe>('pending');

  useEffect(() => {
    const handle = delayRender(`probing footage/${name}.mp4`);
    let live = true;
    fetch(src, {method: 'HEAD'})
      .then((r) => {
        if (live) setState(r.ok ? 'found' : 'missing');
      })
      .catch(() => {
        if (live) setState('missing');
      })
      .finally(() => continueRender(handle));
    return () => {
      live = false;
    };
  }, [src, name]);

  return {state, src};
};

// ---------------------------------------------------------------------------
// shared placeholder chrome
// ---------------------------------------------------------------------------

const Countdown: React.FC<{seconds: number}> = ({seconds}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  const left = Math.max(0, seconds - frame / fps);
  return (
    <div
      style={{
        fontFamily: FONT_MONO,
        fontSize: 26,
        color: COLORS.inkFaint,
        letterSpacing: 2,
      }}
    >
      {left.toFixed(1).padStart(4, '0')}s remaining of {seconds}s
    </div>
  );
};

/** Animated recording reticle - marks the frame as "to be filmed". */
const Reticle: React.FC<{color: string; children: React.ReactNode}> = ({color, children}) => {
  const frame = useCurrentFrame();
  const pulse = 0.45 + 0.35 * (0.5 + 0.5 * Math.sin((frame / 30) * Math.PI * 1.1));
  const L = 54;
  const corner = (x: number, y: number, sx: number, sy: number) => (
    <g key={`${x}-${y}`} stroke={color} strokeWidth={3} fill="none" opacity={pulse}>
      <path d={`M ${x} ${y + sy * L} L ${x} ${y} L ${x + sx * L} ${y}`} />
    </g>
  );
  return (
    <div
      style={{
        position: 'absolute',
        inset: 0,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      <svg
        width={SIZES.width}
        height={SIZES.height}
        style={{position: 'absolute', inset: 0}}
      >
        <rect
          x={118}
          y={118}
          width={SIZES.width - 236}
          height={SIZES.height - 236}
          fill="none"
          stroke={color}
          strokeWidth={1.5}
          strokeDasharray="14 12"
          opacity={0.3}
        />
        {corner(118, 118, 1, 1)}
        {corner(SIZES.width - 118, 118, -1, 1)}
        {corner(118, SIZES.height - 118, 1, -1)}
        {corner(SIZES.width - 118, SIZES.height - 118, -1, -1)}
      </svg>
      {children}
    </div>
  );
};

const SlotLabel: React.FC<{kind: string; color: string}> = ({kind, color}) => (
  <div
    style={{
      fontFamily: FONT_MONO,
      fontSize: 22,
      letterSpacing: 5,
      textTransform: 'uppercase',
      color,
      border: `1px solid ${color}`,
      borderRadius: 4,
      padding: '7px 16px',
      alignSelf: 'flex-start',
    }}
  >
    {kind}
  </div>
);

// ---------------------------------------------------------------------------
// ScreenSlot
// ---------------------------------------------------------------------------

export type ScreenSlotProps = {
  /** file stem under public/footage/ */
  name: string;
  seconds: number;
  /** headline of what the editor must capture */
  capture: string;
  /** the exact commands to run on camera, one per line */
  commands?: string[];
  /** what the viewer must be able to read in the recording */
  mustShow?: string[];
};

export const ScreenSlot: React.FC<ScreenSlotProps> = ({
  name,
  seconds,
  capture,
  commands = [],
  mustShow = [],
}) => {
  const {state, src} = useFootage(name);
  const e = useEnter(2);

  if (state === 'found') {
    return (
      <AbsoluteFill style={{backgroundColor: COLORS.bgDeep}}>
        <OffthreadVideo src={src} style={{width: '100%', height: '100%', objectFit: 'contain'}} />
      </AbsoluteFill>
    );
  }

  return (
    <Backdrop>
      <Reticle color={COLORS.cool}>
        <div
          style={{
            width: 1320,
            display: 'flex',
            flexDirection: 'column',
            gap: 22,
            opacity: e,
            transform: `translateY(${(1 - e) * 12}px)`,
          }}
        >
          <SlotLabel kind="screen recording" color={COLORS.cool} />
          <div style={{fontSize: 52, fontWeight: 300, lineHeight: 1.15, letterSpacing: -0.5}}>
            {capture}
          </div>
          {commands.length ? (
            <div
              style={{
                background: COLORS.panel,
                border: `1px solid ${COLORS.panelEdge}`,
                borderRadius: 10,
                padding: '18px 22px',
                fontFamily: FONT_MONO,
                fontSize: 25,
                lineHeight: 1.65,
                color: COLORS.accent,
              }}
            >
              {commands.map((c, i) => (
                <div key={i}>
                  <span style={{color: COLORS.inkFaint}}>$ </span>
                  {c}
                </div>
              ))}
            </div>
          ) : null}
          {mustShow.length ? (
            <div
              style={{
                fontSize: 27,
                color: COLORS.inkDim,
                fontFamily: FONT_SANS,
                lineHeight: 1.55,
              }}
            >
              Must be legible on screen: {mustShow.join(' · ')}
            </div>
          ) : null}
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              marginTop: 6,
            }}
          >
            <div style={{fontFamily: FONT_MONO, fontSize: 24, color: COLORS.inkFaint}}>
              drop file at{' '}
              <span style={{color: COLORS.accent}}>public/footage/{name}.mp4</span>
            </div>
            <Countdown seconds={seconds} />
          </div>
        </div>
      </Reticle>
    </Backdrop>
  );
};

