// CamSlot
// ---------------------------------------------------------------------------

const PERSON_ACCENT: Record<Person, string> = {
  Rakshit: COLORS.accent,
  Suvrat: COLORS.violet,
  Sumedha: COLORS.green,
};

export type CamSlotProps = {
  person: Person;
  seconds: number;
  /** slug used for the footage file: footage/cam-<slug>.mp4 */
  slug: string;
  /** what they talk about, in a few words */
  topic: string;
  /** the beats they must hit, so the take is usable */
  beats?: string[];
};

export const CamSlot: React.FC<CamSlotProps> = ({person, seconds, slug, topic, beats = []}) => {
  const name = `cam-${slug}`;
  const {state, src} = useFootage(name);
  const e = useEnter(2);
  const frame = useCurrentFrame();
  const {durationInFrames} = useVideoConfig();
  const color = PERSON_ACCENT[person];

  if (state === 'found') {
    const fade = Math.min(
      interpolate(frame, [0, 8], [0, 1], {extrapolateRight: 'clamp'}),
      interpolate(frame, [durationInFrames - 8, durationInFrames], [1, 0], {
        extrapolateLeft: 'clamp',
      })
    );
    return (
      <AbsoluteFill style={{backgroundColor: COLORS.bgDeep, opacity: fade}}>
        <OffthreadVideo src={src} style={{width: '100%', height: '100%', objectFit: 'cover'}} />
        <div
          style={{
            position: 'absolute',
            left: SIZES.margin,
            bottom: 96,
            padding: '12px 22px',
            borderLeft: `3px solid ${color}`,
            background: 'rgba(8,11,16,0.72)',
            fontFamily: FONT_SANS,
          }}
        >
          <div style={{fontSize: 40, fontWeight: 600, color: COLORS.ink}}>{person}</div>
          <div style={{fontSize: 24, color: COLORS.inkDim, marginTop: 2}}>{topic}</div>
        </div>
      </AbsoluteFill>
    );
  }

  return (
    <Backdrop>
      <Reticle color={color}>
        <div
          style={{
            width: 1180,
            display: 'flex',
            flexDirection: 'column',
            gap: 20,
            opacity: e,
            transform: `translateY(${(1 - e) * 12}px)`,
          }}
        >
          <SlotLabel kind="webcam" color={color} />
          <div style={{display: 'flex', alignItems: 'baseline', gap: 24}}>
            <div style={{fontSize: 92, fontWeight: 700, color, letterSpacing: -2}}>{person}</div>
            <div style={{fontSize: 36, color: COLORS.inkDim, fontWeight: 300}}>on camera</div>
          </div>
          <div style={{fontSize: 44, fontWeight: 300, lineHeight: 1.2}}>{topic}</div>
          {beats.length ? (
            <div style={{fontSize: 27, color: COLORS.inkDim, lineHeight: 1.6}}>
              {beats.map((b, i) => (
                <div key={i} style={{display: 'flex', gap: 14}}>
                  <span style={{color, fontFamily: FONT_MONO}}>{String(i + 1)}</span>
                  <span>{b}</span>
                </div>
              ))}
            </div>
          ) : null}
          <div
            style={{
              display: 'flex',
              justifyContent: 'space-between',
              alignItems: 'center',
              marginTop: 8,
            }}
          >
            <div style={{fontFamily: FONT_MONO, fontSize: 24, color: COLORS.inkFaint}}>
              waist-up, eyes on lens, 1080p &#8805; 30fps &#8212; drop at{' '}
              <span style={{color}}>public/footage/{name}.mp4</span>
            </div>
            <Countdown seconds={seconds} />
          </div>
        </div>
      </Reticle>
    </Backdrop>
  );
};
